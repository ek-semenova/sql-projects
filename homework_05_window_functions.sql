--ЗАДАНИЕ №1
--С помощью оконной функции выведите для каждого сотрудника сумму продаж за август 2005 года 
--с нарастающим итогом по каждому сотруднику и по каждой дате продажи (без учёта времени) 
--с сортировкой по дате.
--В результирующей таблице должны быть следующие столбцы: Фамилия и имя сотрудника в виде 
--одного значения, сумма продаж на каждый день, накопительный итог.

SELECT 
    s.last_name || ' ' || s.first_name AS staff_name,
    DATE(p.payment_date) AS sale_date,
    SUM(p.amount) AS daily_total,
    SUM(SUM(p.amount)) OVER (
        PARTITION BY s.staff_id 
        ORDER BY DATE(p.payment_date)
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS running_total
FROM payment p
JOIN staff s ON p.staff_id = s.staff_id
WHERE DATE(p.payment_date) BETWEEN '2005-08-01' AND '2005-08-31'
GROUP BY s.staff_id, s.last_name, s.first_name, DATE(p.payment_date)
ORDER BY staff_name, sale_date;

